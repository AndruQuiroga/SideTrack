"""Render docs/STATUS.md from docs/status.yaml plus facts read from the repository.

Usage:
    python scripts/gen_status.py          # write docs/STATUS.md
    python scripts/gen_status.py --check  # exit 1 if status.yaml is invalid or STATUS.md is stale

Spec: platform/status-report.
"""

from __future__ import annotations

import argparse
import logging
import os
import re
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "status.yaml"
OUTPUT = ROOT / "docs" / "STATUS.md"
STATUSES = ("works", "partial", "broken", "stub", "absent")
TASK_PATTERN = re.compile(r"^\s*- \[( |x|X)\]", re.MULTILINE)


def validate(data: dict[str, Any], root: Path = ROOT) -> list[str]:
    """Return a list of problems; empty means valid."""

    errors: list[str] = []
    for group in data.get("groups", []):
        for item in group.get("items", []):
            name = item.get("capability", "<unnamed>")
            status = item.get("status")
            if status not in STATUSES:
                allowed = ", ".join(STATUSES)
                errors.append(f"{name}: unknown status {status!r} (use one of {allowed})")
            evidence = item.get("evidence") or []
            if status == "works" and not evidence:
                errors.append(f"{name}: 'works' needs at least one evidence path")
            for path in evidence:
                if not any(root.glob(path)):
                    errors.append(f"{name}: evidence path does not exist: {path}")
    return errors


def api_routes() -> list[str]:
    """`METHODS path` for every API route, sorted."""

    os.environ["SIDETRACK_ENV"] = "development"
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from sidetrack.api.main import create_app

    # Only the route table is needed; the dev-mode auth warning is noise here.
    logger = logging.getLogger("sidetrack.api.main")
    previous_level = logger.level
    logger.setLevel(logging.ERROR)
    try:
        app = create_app()
    finally:
        logger.setLevel(previous_level)

    lines = set()
    for route in app.routes:
        methods = sorted(set(getattr(route, "methods", None) or []) - {"HEAD", "OPTIONS"})
        path = getattr(route, "path", "")
        if methods and not path.startswith(("/docs", "/redoc", "/openapi")):
            lines.add(f"{','.join(methods)} {path}")
    return sorted(lines, key=lambda line: (line.split(" ", 1)[1], line))


def migration_head(root: Path = ROOT) -> str:
    revisions: dict[str, str | None] = {}
    for path in (root / "migrations" / "versions").glob("*.py"):
        text = path.read_text(encoding="utf-8")
        revision = re.search(r'^revision\s*=\s*["\']([^"\']+)', text, re.MULTILINE)
        down = re.search(r'^down_revision\s*=\s*["\']([^"\']+)', text, re.MULTILINE)
        if revision:
            revisions[revision.group(1)] = down.group(1) if down else None
    heads = sorted(set(revisions) - {d for d in revisions.values() if d})
    return ", ".join(heads) if heads else "none"


def specs(root: Path = ROOT) -> list[str]:
    base = root / "openspec" / "specs"
    return sorted(p.parent.relative_to(base).as_posix() for p in base.glob("**/spec.md"))


def changes(root: Path = ROOT) -> list[tuple[str, int, int]]:
    result = []
    for path in sorted((root / "openspec" / "changes").iterdir()):
        if not path.is_dir() or path.name == "archive":
            continue
        tasks = path / "tasks.md"
        marks = TASK_PATTERN.findall(tasks.read_text(encoding="utf-8")) if tasks.exists() else []
        result.append((path.name, sum(m in "xX" for m in marks), len(marks)))
    return result


def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell (no pipes, newlines or HTML-like tags)."""
    return (
        text.replace("|", "\\|")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\n", " ")
        .strip()
    )


def render(data: dict[str, Any], root: Path = ROOT, routes: list[str] | None = None) -> str:
    routes = api_routes() if routes is None else routes
    out = [
        "# Status",
        "",
        "<!-- Generated by scripts/gen_status.py from docs/status.yaml. Do not edit by hand. -->",
        "",
        f"What actually works, reviewed {data['reviewed']}. Edit `docs/status.yaml` and run "
        "`python scripts/gen_status.py`; CI fails if this page is stale. A **works** row must cite "
        "evidence that exists in the repo.",
        "",
        "Statuses: **works** (implemented end to end), **partial** (known gaps or untested), "
        "**broken** (implemented but cannot succeed), **stub** (placeholder), **absent**.",
    ]
    for group in data["groups"]:
        out += ["", f"## {group['name']}", "", "| Capability | Status | Notes | Evidence |"]
        out.append("| --- | --- | --- | --- |")
        for item in group["items"]:
            evidence = ", ".join(f"`{p}`" for p in item.get("evidence") or [])
            out.append(
                f"| {_cell(item['capability'])} | {item['status']} | "
                f"{_cell(str(item.get('notes', '')))} | {evidence} |"
            )

    out += ["", "## Facts from the repository", "", "### In-flight changes", ""]
    in_flight = changes(root)
    out += [f"- `{name}`: {done}/{total} tasks" for name, done, total in in_flight] or ["None."]
    out += ["", "### Specs", ""]
    no_specs = ["None yet (specs land when changes are archived)."]
    out += [f"- `{name}`" for name in specs(root)] or no_specs
    out += ["", f"### Migration head\n\n`{migration_head(root)}`", "", "### API routes", "", "```"]
    out += routes
    out += ["```", ""]
    return "\n".join(out)


def load(path: Path = SOURCE) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if STATUS.md is stale")
    args = parser.parse_args(argv)

    data = load()
    errors = validate(data)
    if errors:
        print("docs/status.yaml is invalid:\n  " + "\n  ".join(errors))
        return 1

    rendered = render(data)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != rendered:
            print("docs/STATUS.md is stale. Run: python scripts/gen_status.py")
            return 1
        print("docs/STATUS.md is current.")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
