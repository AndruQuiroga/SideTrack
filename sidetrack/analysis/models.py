"""Analysis owns these table mappings."""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import TYPE_CHECKING

from pgvector.sqlalchemy import VECTOR
from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy import Enum as SAEnum
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from sidetrack.db import Base
from sidetrack.types import AudioKind, AudioSource, AudioVerification

if TYPE_CHECKING:
    from sidetrack.catalog.models import Album, Track
    from sidetrack.identity.models import User


class TrackFeature(Base):
    __tablename__ = "track_features"

    track_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("tracks.id", ondelete="CASCADE"),
        primary_key=True,
    )
    energy: Mapped[float | None] = mapped_column(Float)
    valence: Mapped[float | None] = mapped_column(Float)
    danceability: Mapped[float | None] = mapped_column(Float)
    tempo: Mapped[float | None] = mapped_column(Float)
    acousticness: Mapped[float | None] = mapped_column(Float)
    instrumentalness: Mapped[float | None] = mapped_column(Float)
    genres: Mapped[list[str] | None] = mapped_column(JSON)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    track: Mapped[Track] = relationship(back_populates="features")


class TasteProfile(Base):
    __tablename__ = "taste_profiles"
    __table_args__ = (UniqueConstraint("user_id", "scope", name="uq_taste_profiles_scope"),)

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        primary_key=True,
    )
    scope: Mapped[str] = mapped_column(String(64), default="all_time", nullable=False)
    genre_histogram: Mapped[dict | None] = mapped_column(JSON)
    feature_means: Mapped[dict | None] = mapped_column(JSON)
    time_of_day_histogram: Mapped[dict | None] = mapped_column(JSON)
    last_computed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    user: Mapped[User] = relationship(back_populates="taste_profiles")


class Compatibility(Base):
    """Pairwise taste-compatibility cache between two users.

    Currently populated only by ``analysis.compatibility.upsert_compatibility()`` which
    is not yet wired to any route or worker job; social features are shelved until
    listening data is real (see docs/STATUS.md).  Rows are ordered so that
    ``user_a_id < user_b_id`` to guarantee a single canonical row per pair.
    """

    __tablename__ = "compatibility"
    __table_args__ = (UniqueConstraint("user_a_id", "user_b_id", name="uq_compatibility_pair"),)

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_a_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    user_b_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    score: Mapped[float] = mapped_column(Float, default=0.0)
    details: Mapped[dict | None] = mapped_column(JSON)
    computed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    user_a: Mapped[User] = relationship(
        "User", foreign_keys=[user_a_id], back_populates="compatibility_a"
    )
    user_b: Mapped[User] = relationship(
        "User", foreign_keys=[user_b_id], back_populates="compatibility_b"
    )


class UserRecommendation(Base):
    """Per-user album recommendation generated by the analysis pipeline.

    Not yet populated by any route or worker.  Reserved for a future recommendation
    engine.  Each row pairs a user with an album, a numeric ``score`` (higher =
    stronger recommendation), and an optional human-readable ``reason``.
    """

    __tablename__ = "user_recommendations"
    __table_args__ = (UniqueConstraint("user_id", "album_id", name="uq_user_recommendations_pair"),)

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    album_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("albums.id", ondelete="CASCADE"), nullable=False
    )
    score: Mapped[float] = mapped_column(Float, default=0.0)
    reason: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    user: Mapped[User] = relationship(back_populates="recommendations")
    album: Mapped[Album] = relationship(back_populates="recommendations")


def _enum(enum_type, name: str) -> SAEnum:
    return SAEnum(enum_type, name=name, values_callable=lambda e: [m.value for m in e])


class AudioAsset(Base):
    """An audio file fetched on the owner's request (ADR 0007).

    ``path`` is relative to ``SIDETRACK_AUDIO_DIR``; the file itself never leaves the
    owner's disk. Rows outlive their files (``file_deleted_at``) so derived results keep
    their reference.
    """

    __tablename__ = "audio_assets"
    __table_args__ = (
        UniqueConstraint("sha256", name="uq_audio_assets_sha256"),
        UniqueConstraint("source", "source_ref", name="uq_audio_assets_source_ref"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    track_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("tracks.id", ondelete="SET NULL"), index=True
    )
    seed_artist: Mapped[str] = mapped_column(Text, nullable=False)
    seed_title: Mapped[str] = mapped_column(Text, nullable=False)
    source: Mapped[AudioSource] = mapped_column(_enum(AudioSource, "audio_source"), nullable=False)
    source_ref: Mapped[str] = mapped_column(Text, nullable=False)
    kind: Mapped[AudioKind] = mapped_column(_enum(AudioKind, "audio_kind"), nullable=False)
    path: Mapped[str] = mapped_column(Text, nullable=False)
    format: Mapped[str] = mapped_column(String(16), nullable=False)
    duration_s: Mapped[float | None] = mapped_column(Float)
    verification: Mapped[AudioVerification] = mapped_column(
        _enum(AudioVerification, "audio_verification"), nullable=False
    )
    acoustid_score: Mapped[float | None] = mapped_column(Float)
    recording_mbid: Mapped[str | None] = mapped_column(String(36))
    fetched_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=lambda: datetime.now(UTC)
    )
    file_deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class AudioEmbedding(Base):
    """One model's embedding of one audio asset (ADR 0004; openspec analysis/audio-embeddings).

    ``embedding`` is an untyped pgvector column so models of different dimensions share the
    table; ``dim`` records the length and a check keeps them in step. Vectors are compared
    only within one ``model``, ``checkpoint_revision`` and ``pipeline``.
    """

    __tablename__ = "audio_embeddings"
    __table_args__ = (
        UniqueConstraint("asset_id", "model", name="uq_audio_embeddings_asset_model"),
        CheckConstraint("vector_dims(embedding) = dim", name="ck_audio_embeddings_dim"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    asset_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("audio_assets.id", ondelete="CASCADE"), nullable=False
    )
    model: Mapped[str] = mapped_column(String(64), nullable=False)
    checkpoint_revision: Mapped[str] = mapped_column(String(64), nullable=False)
    pipeline: Mapped[str] = mapped_column(String(64), nullable=False)
    dim: Mapped[int] = mapped_column(Integer, nullable=False)
    embedding: Mapped[list[float]] = mapped_column(VECTOR(), nullable=False)
    # The background job that produced it. Not a foreign key: finished jobs are cleaned up.
    job_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True))
    embedded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=lambda: datetime.now(UTC)
    )


