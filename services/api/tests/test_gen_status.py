"""Spec: platform/status-report (openspec/changes/generated-status-page)."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location("gen_status", ROOT / "scripts" / "gen_status.py")
gen_status = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gen_status)


def _data(**item):
    base = {"capability": "Thing", "status": "partial"}
    return {"reviewed": "2026-10-25", "groups": [{"name": "G", "items": [{**base, **item}]}]}


def test_works_without_evidence_is_an_error():
    errors = gen_status.validate(_data(status="works"))
    assert errors == ["Thing: 'works' needs at least one evidence path"]


def test_missing_evidence_path_is_an_error():
    errors = gen_status.validate(_data(status="works", evidence=["services/nope_test.py"]))
    assert errors == ["Thing: evidence path does not exist: services/nope_test.py"]


def test_unknown_status_is_an_error():
    errors = gen_status.validate(_data(status="mostly"))
    assert len(errors) == 1 and "unknown status 'mostly'" in errors[0]


def test_valid_entry_has_no_errors():
    assert gen_status.validate(_data(status="works", evidence=["scripts/gen_status.py"])) == []


def test_committed_yaml_is_valid():
    assert gen_status.validate(gen_status.load()) == []


def test_render_is_deterministic_and_lists_facts():
    data = gen_status.load()
    first = gen_status.render(data)
    second = gen_status.render(data)

    assert first == second
    assert "Generated by scripts/gen_status.py" in first
    assert "GET /health" in first
    assert "### Migration head" in first
    assert "### In-flight changes" in first
    assert "### Specs" in first


def test_committed_status_page_is_current():
    assert gen_status.main(["--check"]) == 0, "Run: python scripts/gen_status.py"
